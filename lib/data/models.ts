function appleIphone(
  id: string,
  name: string,
  base: { screen: number; battery: number; camera: number; charge: number },
): DeviceModel {
  return {
    id: `apple-${id}`,
    slug: id,
    brandId: "apple",
    name,
    category: "smartphone",
    repairs: {
      screen: base.screen,
      battery: base.battery,
      camera: base.camera,
      chargePort: base.charge,
      speaker: 59,
      desox: 79,
      software: 39,
      unlock: 49,
      other: 0,
    },
  };
}

